#!/usr/bin/env python3
"""
Export HEMIT real CD3 stains + pseudo YOLO boxes for training (train/val only).

Labels come from CD3+ nuclei on real multiplex label TIFFs — never from generated images.

Usage:
  python scripts/hemit_yolo_prepare_cd3_dataset.py \\
    --hemit-root /path/to/hemit \\
    --outdir datasets/hemit_cd3_yolo

  python scripts/hemit_yolo_prepare_cd3_dataset.py \\
    --dataroot ./datasets/hemit \\
    --outdir datasets/hemit_cd3_yolo
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import tifffile
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts.hemit_eval_path import setup_hemit_eval_path

setup_hemit_eval_path()

from hemit_eval.yolo_cd3 import cd3_positive_boxes, stack_to_cd3_uint8


def _load_stack(path: Path) -> np.ndarray:
    suffix = path.suffix.lower()
    if suffix in (".tif", ".tiff"):
        arr = tifffile.imread(path)
    else:
        arr = np.array(Image.open(path).convert("RGB"))
    if arr.ndim == 2:
        arr = np.stack([arr, arr, arr], axis=-1)
    arr = arr[..., :3].astype(np.float32)
    if arr.max() <= 1.0:
        arr *= 255.0
    return arr


def iter_label_paths(hemit_root: Path | None, dataroot: Path | None, split: str) -> list[Path]:
    if hemit_root is not None:
        lab_dir = hemit_root / split / "label"
        if not lab_dir.is_dir():
            return []
        paths: list[Path] = []
        for pattern in ("*.tif", "*.tiff", "*.TIF", "*.TIFF", "*.png", "*.PNG"):
            paths.extend(sorted(lab_dir.glob(pattern)))
        return paths
    if dataroot is not None:
        b_dir = dataroot / f"{split}B"
        if not b_dir.is_dir():
            return []
        paths = []
        for pattern in ("*.tif", "*.tiff", "*.TIF", "*.TIFF", "*.png", "*.PNG"):
            paths.extend(sorted(b_dir.glob(pattern)))
        return paths
    return []


def export_split(
    paths: list[Path],
    images_dir: Path,
    labels_dir: Path,
    *,
    min_boxes: int = 1,
    bbox_pad: int = 8,
    min_box_px: int = 24,
) -> tuple[int, int]:
    images_dir.mkdir(parents=True, exist_ok=True)
    labels_dir.mkdir(parents=True, exist_ok=True)
    n_images = 0
    n_boxes = 0
    for src in paths:
        stack = _load_stack(src)
        h, w = stack.shape[:2]
        boxes = cd3_positive_boxes(stack, pad=bbox_pad, min_side=min_box_px)
        if len(boxes) < min_boxes:
            continue
        stem = src.stem
        img_path = images_dir / f"{stem}.png"
        lbl_path = labels_dir / f"{stem}.txt"
        Image.fromarray(stack_to_cd3_uint8(stack)).save(img_path)
        lines = [b.to_yolo_line(w, h) for b in boxes]
        lbl_path.write_text("\n".join(lines) + ("\n" if lines else ""), encoding="utf-8")
        n_images += 1
        n_boxes += len(boxes)
    return n_images, n_boxes


def write_dataset_yaml(outdir: Path, yaml_path: Path) -> None:
    content = f"""# Auto-generated by hemit_yolo_prepare_cd3_dataset.py
path: {outdir.resolve()}
train: images/train
val: images/val

names:
  0: cd3_positive
"""
    yaml_path.write_text(content, encoding="utf-8")


def main() -> None:
    p = argparse.ArgumentParser(description="Prepare HEMIT CD3 YOLO dataset from real stains.")
    src = p.add_mutually_exclusive_group(required=True)
    src.add_argument("--hemit-root", type=str, help="Official HEMIT root (train/label, val/label)")
    src.add_argument("--dataroot", type=str, help="pix2pix dataroot (trainB, valB)")
    p.add_argument("--outdir", type=str, default="datasets/hemit_cd3_yolo")
    p.add_argument("--splits", type=str, default="train,val", help="Comma-separated splits to export")
    p.add_argument("--min-boxes", type=int, default=1,
                   help="Keep only tiles with at least this many CD3+ boxes (default: 1)")
    p.add_argument("--bbox-pad", type=int, default=8, help="Pixel padding around nucleus bbox")
    p.add_argument("--min-box-px", type=int, default=24, help="Minimum box side in pixels for YOLO")
    args = p.parse_args()

    hemit_root = Path(args.hemit_root).expanduser().resolve() if args.hemit_root else None
    dataroot = Path(args.dataroot).expanduser().resolve() if args.dataroot else None
    outdir = Path(args.outdir).expanduser().resolve()
    splits = [s.strip() for s in args.splits.split(",") if s.strip()]

    totals: dict[str, tuple[int, int]] = {}
    for split in splits:
        paths = iter_label_paths(hemit_root, dataroot, split)
        if not paths:
            print(f"[warn] no label images for split={split}")
            continue
        n_img, n_box = export_split(
            paths,
            outdir / "images" / split,
            outdir / "labels" / split,
            min_boxes=args.min_boxes,
            bbox_pad=args.bbox_pad,
            min_box_px=args.min_box_px,
        )
        totals[split] = (n_img, n_box)
        print(f"  {split}: {n_img} images, {n_box} CD3+ boxes")

    if "train" not in totals or totals["train"][0] == 0:
        raise SystemExit("No training images exported — check --hemit-root or --dataroot")

    yaml_path = outdir / "hemit_cd3.yaml"
    write_dataset_yaml(outdir, yaml_path)
    print(f"Wrote {yaml_path}")
    print("Next: python scripts/hemit_yolo_train_cd3.py --data", yaml_path)


if __name__ == "__main__":
    main()
